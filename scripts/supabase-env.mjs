// Reads the LOCAL Supabase stack's connection info without printing secrets.
//   node scripts/supabase-env.mjs status    -> redacted status table
//   node scripts/supabase-env.mjs env-local -> writes .env.local (publishable key only)
// Library use: import { getLocalSupabaseEnv } from './supabase-env.mjs'
import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
// Run the project-local CLI through node directly: no shell, no argument concatenation.
const SUPABASE_CLI = path.join(root, 'node_modules', 'supabase', 'dist', 'supabase.js')

// Reads and parses `supabase status` once. Errors are generic on purpose: the raw output
// contains secret keys and must never end up in an error message.
function readStatus(stderr = 'ignore') {
  let raw
  try {
    raw = execFileSync(process.execPath, [SUPABASE_CLI, 'status', '-o', 'json'], {
      cwd: root,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', stderr],
    })
  } catch {
    throw new Error('Local Supabase is not running. Start it with `npm run db:start`.')
  }
  try {
    return JSON.parse(raw.slice(raw.indexOf('{')))
  } catch {
    throw new Error('Could not parse `supabase status` output.')
  }
}

function assertLocal(url) {
  const host = new URL(url).hostname
  if (!['127.0.0.1', 'localhost', 'host.docker.internal'].includes(host)) {
    throw new Error(`Refusing non-local Supabase URL: ${host}`)
  }
}

export function getLocalSupabaseEnv() {
  if (process.env.SUPABASE_URL && process.env.SUPABASE_PUBLISHABLE_KEY) {
    assertLocal(process.env.SUPABASE_URL)
    return { url: process.env.SUPABASE_URL, publishableKey: process.env.SUPABASE_PUBLISHABLE_KEY }
  }
  const json = readStatus()
  const url = json.API_URL
  const publishableKey = json.PUBLISHABLE_KEY ?? json.ANON_KEY
  if (!url || !publishableKey)
    throw new Error('Could not read API_URL / PUBLISHABLE_KEY from supabase status')
  assertLocal(url)
  return { url, publishableKey }
}

/**
 * LOCAL admin (secret) key for node-side test setup only. Never print, log, or put it into
 * process.env / VITE_* / files. Always read from the local stack and asserted to be local.
 */
export function getLocalSupabaseAdminEnv() {
  const json = readStatus()
  const url = json.API_URL
  const secretKey = json.SECRET_KEY ?? json.SERVICE_ROLE_KEY
  if (!url || !secretKey)
    throw new Error('Could not read API_URL / SECRET_KEY from supabase status')
  assertLocal(url)
  const override = process.env.SUPABASE_URL
  if (override && new URL(override).origin !== new URL(url).origin) {
    throw new Error(
      'SUPABASE_URL differs from the local stack API_URL; refusing to use the admin key.',
    )
  }
  return { url, secretKey }
}

// Fixed mask: no characters of the value are shown, except a known `sb_*_` key-type prefix.
const redact = (v) => {
  const prefix = /^sb_[a-z]+_/.exec(v)
  return `${prefix ? prefix[0] : ''}(redacted)`
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const mode = process.argv[2] ?? 'status'
  if (mode === 'env-local') {
    const { url, publishableKey } = getLocalSupabaseEnv()
    writeFileSync(
      path.join(root, '.env.local'),
      `# Generated by npm run env:local — LOCAL stack only, gitignored.\nVITE_SUPABASE_URL=${url}\nVITE_SUPABASE_PUBLISHABLE_KEY=${publishableKey}\n`,
    )
    console.log('Wrote .env.local (VITE_SUPABASE_URL, VITE_SUPABASE_PUBLISHABLE_KEY).')
  } else {
    const json = readStatus('inherit')
    for (const [k, v] of Object.entries(json)) {
      const secret = /KEY|SECRET|TOKEN|PASSWORD/i.test(k) || /:\/\/[^@]+@/.test(String(v))
      console.log(
        `${k.padEnd(18)} ${secret ? redact(String(v).replace(/\/\/[^@]+@/, '//***@')) : v}`,
      )
    }
  }
}
